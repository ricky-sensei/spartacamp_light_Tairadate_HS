# 巨大文字でメッセージを表示するプログラム
# message の中身を変えると、表示される文字が変わるよ

message = "HELLO WORLD"

# 1文字ずつ、5行ぶんの「形」を辞書型で登録しておく
moji = {
    "H": [
        "#   #",
        "#   #",
        "#####",
        "#   #",
        "#   #",
    ],
    "E": [
        "#####",
        "#    ",
        "#### ",
        "#    ",
        "#####",
    ],
    "L": [
        "#    ",
        "#    ",
        "#    ",
        "#    ",
        "#####",
    ],
    "O": [
        " ### ",
        "#   #",
        "#   #",
        "#   #",
        " ### ",
    ],
    "W": [
        "#   #",
        "#   #",
        "# # #",
        "## ##",
        "#   #",
    ],
    "R": [
        "#### ",
        "#   #",
        "#### ",
        "#  # ",
        "#   #",
    ],
    "D": [
        "#### ",
        "#   #",
        "#   #",
        "#   #",
        "#### ",
    ],
    " ": [
        "   ",
        "   ",
        "   ",
        "   ",
        "   ",
    ],
}

# 上から1行ずつ、全部の文字の形をくっつけて表示する
for gyou in range(5):
    line = ""
    for c in message:
        line = line + moji[c][gyou] + "  "
    print(line)
